  <svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" viewBox="0 0 48 48" :class="cls" :style="innerStyle" :stroke-width="props.strokeWidth" :stroke-linecap="props.strokeLinecap" :stroke-linejoin="props.strokeLinejoin" @click="emit('click', $event)"><path d="M31.587 31.485A9.98 9.98 0 0 0 24 28a9.98 9.98 0 0 0-7.586 3.485M37.255 25.822A17.95 17.95 0 0 0 24 20a17.95 17.95 0 0 0-13.256 5.822M43.618 19.449C38.696 14.246 31.728 11 24 11S9.304 14.246 4.383 19.449"/><path fill="currentColor" stroke="none" d="M27.536 35.465a5 5 0 0 0-7.071 0L24 39z"/></svg>
